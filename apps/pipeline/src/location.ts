const has = (t: string, words: string[]) => words.some((w) => t.includes(` ${w} `));

export type Place =
  | {
      keep: true;
      mode: "onsite" | "hybrid" | "remote";
      scope: "office" | "country" | "europe" | "worldwide";
      countries: string[];
    }
  | { keep: false; why: string };

// An office in a known European country, or remote open to Europe. Remote with no region at all is dropped: on a
// US company's board it almost always means the US.
export function where(
  text: string,
  { remote = false, hybrid = false, codes = [] as (string | null | undefined)[] } = {},
): Place {
  const found = new Set(
    codes
      .filter((c): c is string => !!c)
      .map((c) => c.toUpperCase())
      .map((c) => (c.length === 3 ? ISO3[c] : c === "UK" ? "GB" : c))
      .filter((c): c is string => !!c && KNOWN.has(c)),
  );
  let away = false;
  for (const seg of text.split(/;|\||\n|·|•|\/|\bor\b/i)) {
    const t = ` ${norm(seg)} `;
    if (!t.trim()) continue;
    const countries = Object.entries(COUNTRY)
      .filter(([k]) => t.includes(` ${k} `))
      .map(([, c]) => c);
    const cities = Object.entries(CITY)
      .filter(([k]) => t.includes(` ${k} `))
      .map(([, c]) => c);
    const codesIn = (seg.match(/\b[A-Z]{2,3}\b/g) ?? [])
      .map((c) => (c.length === 3 ? ISO3[c] : CODE2.has(c) ? (c === "UK" ? "GB" : c) : undefined))
      .filter((c): c is string => !!c)
      .filter((c) => !STATE_TOO.has(c) || cities.includes(c) || !new RegExp(`,\\s*${c}\\b`).test(seg));
    const elsewhere = has(t, ELSEWHERE) || US_STATE.test(seg);
    if (countries.length || codesIn.length) [...countries, ...codesIn].forEach((c) => found.add(c));
    else if (cities.length && !elsewhere) cities.forEach((c) => found.add(c));
    if (elsewhere && !countries.length && !codesIn.length) away = true;
  }
  const t = ` ${norm(text)} `;
  const isRemote = remote || has(t, REMOTE_W);
  const isHybrid = hybrid || /hybrid/i.test(text);
  const countries = [...found].sort();
  if (isRemote && !isHybrid) {
    if (has(t, GLOBAL_W)) return { keep: true, mode: "remote", scope: "worldwide", countries };
    if (has(t, EUROPE_W) || /utc\s*[+±-]?\s*[0-3](?!\d)/i.test(text))
      return { keep: true, mode: "remote", scope: "europe", countries };
    if (countries.length) return { keep: true, mode: "remote", scope: "country", countries };
    return { keep: false, why: away ? "remote, limited to another region" : "remote, region unknown" };
  }
  if (countries.length)
    return { keep: true, mode: isHybrid ? "hybrid" : "onsite", scope: "office", countries };
  return { keep: false, why: away ? "office outside Europe" : "location unknown" };
}

export const inScope = (p: Place) =>
  p.keep && (p.scope === "europe" || p.scope === "worldwide" || p.countries.some((c) => SCOPE.has(c)));
